                    {{-- 1. Introduction --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">1. Introduction</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            The <strong>CLSU Siel Cart</strong> is the official online merchandise platform operated under the auxiliary and business operations mandate of Central Luzon State University (CLSU), through its Office of Business Affairs. We are committed to protecting the privacy and personal data of our users — external customers, students, faculty, staff, and other members of the CLSU community — in accordance with Republic Act No. 10173, otherwise known as the Data Privacy Act of 2012, its Implementing Rules and Regulations, and other applicable issuances of the National Privacy Commission (NPC).
                        </p>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            This Data Privacy Notice and Consent describes what personal data we collect through the System, why we collect it, how it is used, stored, shared, and protected, and what rights you have as a data subject. Please read this Notice carefully before creating an account, placing an order, or otherwise using the System.
                        </p>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            This Notice is issued consistent with, and is intended to operate alongside, the University’s existing data privacy infrastructure — including the CLSU Data Privacy Office and the University’s designated Data Protection Officer (DPO) — as reflected in other official CLSU systems (see <a href="https://clsu.edu.ph/data-privacy" target="_blank" rel="noopener noreferrer" class="text-[var(--color-primary)] underline">clsu.edu.ph/data-privacy</a>).
                        </p>
                    </section>

                    {{-- 2. Scope and Coverage of the System --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">2. Scope and Coverage of the System</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            The CLSU Siel Cart is an order and pickup-only platform. It allows verified users to browse and order official CLSU merchandise, apparel, academic regalia, memorabilia, and daily accessories online, pay for their orders, and pick up their items within the CLSU campus. This Notice covers all personal data processed through:
                        </p>
                        <ul class="mt-3 list-disc space-y-2 pl-5 text-base leading-8 text-slate-600">
                            <li>Account registration, login, and profile management;</li>
                            <li>Product browsing, ordering, and order fulfillment (pickup only — the System does not collect delivery or shipping addresses);</li>
                            <li>Payment processing (Cash on Pickup only — the System does not accept or process online payments);</li>
                            <li>Product reviews and ratings submitted after order pickup;</li>
                            <li>Return, exchange, and refund requests, including in-person processing at the University Business Affairs and Production (UBAP) office;</li>
                            <li>Administrative functions performed by authorized University personnel (StraCom Admin, UBAP Admin, and Super Admin roles).</li>
                        </ul>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            Because the System is pickup-only, no delivery or courier-related personal data (such as a shipping address for a third-party courier) is collected or shared with any logistics provider. For the same reason, all payments, returns, exchanges, and cash refunds are completed in person at UBAP. The System itself is used only to place orders and to file, track, and schedule pick up, return, and refund matters — it does not process any online payment or automatic online refund.
                        </p>
                    </section>

                    {{-- 3. Personal Data We Collect --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">3. Personal Data We Collect</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            We collect only the personal data reasonably necessary to operate the system. Depending on how you use the CLSU Siel Cart, this may include:
                        </p>
                        
                        <h3 class="mt-4 text-lg font-semibold text-slate-800">3.1 Account and Profile Information</h3>
                        <ul class="mt-2 list-disc space-y-1 pl-5 text-base leading-8 text-slate-600">
                            <li>Full name</li>
                            <li>Email address (institutional or personal)</li>
                            <li>Phone number (optional)</li>
                            <li>Date of Birth</li>
                            <li>Account credentials (passwords are encrypted/hashed and never visible, even to System administrators)</li>
                        </ul>

                        <h3 class="mt-4 text-lg font-semibold text-slate-800">3.2 Order and Transaction Information</h3>
                        <ul class="mt-2 list-disc space-y-1 pl-5 text-base leading-8 text-slate-600">
                            <li>Order details — items purchased, quantity, price, and order status (pending, ready for pickup, completed, cancelled)</li>
                            <li>Order/Claim reference number and pickup confirmation</li>
                            <li>Payment status and transaction reference number</li>
                            <li>Official Receipt reference issued upon order pickup</li>
                        </ul>

                        <h3 class="mt-4 text-lg font-semibold text-slate-800">3.3 Reviews and Feedback</h3>
                        <p class="mt-2 text-base leading-8 text-slate-600">
                            If you choose to leave a product review after picking up your order, we collect the content of your review, your rating, and the date submitted. Reviews are associated with your account and may be visible to other users of the System.
                        </p>

                        <h3 class="mt-4 text-lg font-semibold text-slate-800">3.4 Return, Exchange, and Refund Information</h3>
                        <p class="mt-2 text-base leading-8 text-slate-600">
                            If you request a return, exchange, or refund, we additionally collect:
                        </p>
                        <ul class="mt-2 list-disc space-y-1 pl-5 text-base leading-8 text-slate-600">
                            <li>The order and specific item(s) you are returning;</li>
                            <li>Your selected reason for the return (Defective, Damaged, or Not as Described);</li>
                            <li>Your written description of the problem;</li>
                            <li>Photo and video evidence uploaded in support of your request (at least 1 and up to 4 photos in JPG/PNG format up to 5MB each, and an optional video up to 1 minute in duration), which may show the item, defect/damage, and tag/label;</li>
                            <li>Your scheduled date and time slot for bringing the item to UBAP;</li>
                            <li>The status history of your request (e.g., Pending Review, Approved, Rejected, Item Received – Under Quality Check, Completed, Denied);</li>
                            <li>The outcome of UBAP's in-person quality check and staff inspection notes;</li>
                            <li>Any additional details or updated photos provided for requests requiring further review.</li>
                        </ul>

                        <h3 class="mt-4 text-lg font-semibold text-slate-800">3.5 System and Usage Information</h3>
                        <p class="mt-2 text-base leading-8 text-slate-600">
                            Like most web applications, the System may automatically record basic technical information (such as login timestamps and session activity) to maintain security and troubleshoot issues.
                        </p>
                    </section>

                    {{-- 4. Why We Collect and Process Your Personal Data --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">4. Why We Collect and Process Your Personal Data</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            We process your personal data for the following purposes, consistent with the principles of transparency, legitimate purpose, and proportionality under the DPA:
                        </p>
                        <ul class="mt-3 list-disc space-y-2 pl-5 text-base leading-8 text-slate-600">
                            <li>To create and manage your CLSU Siel Cart account;</li>
                            <li>To verify your identity and confirm you meet applicable operational requirements;</li>
                            <li>To process, fulfill, and allow you to pick up your orders within CLSU;</li>
                            <li>To allow you to submit and view product reviews;</li>
                            <li>To receive, evaluate, and act on return, exchange, and refund requests (including verifying submission windows, inspecting proof media, and notifying decisions);</li>
                            <li>To schedule and manage your in-person visit to UBAP for item drop-off, quality inspection, and release of cash refunds or exchange items;</li>
                            <li>To record and maintain UBAP's quality check results and Return/Refund status history;</li>
                            <li>To communicate regarding your account, orders, or System updates;</li>
                            <li>To maintain the security, integrity, and proper functioning of the System;</li>
                            <li>To comply with applicable laws, University policies, and legitimate requests from government authorities.</li>
                        </ul>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            The legal bases for this processing include your consent, the necessity of processing to fulfill a transaction you have requested, and the legitimate interests of the University in operating an official campus merchandise service.
                        </p>
                    </section>

                    {{-- 5. Payment Information (Cash on Pickup) --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">5. Payment Information (Cash on Pickup)</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            The CLSU Siel Cart does not accept or process online payments, and no third-party payment gateway is used. All orders are paid for in cash, at the time of pickup, at UBAP.
                        </p>
                        <h3 class="mt-4 text-lg font-semibold text-slate-800">5.1 What Payment Data We Collect</h3>
                        <p class="mt-2 text-base leading-8 text-slate-600">
                            Because payment happens in person, the System does not collect or store any card numbers, e-wallet credentials, or banking details. The System records only the amount due and amount paid.
                        </p>
                        <h3 class="mt-4 text-lg font-semibold text-slate-800">5.2 Refunds</h3>
                        <p class="mt-2 text-base leading-8 text-slate-600">
                            If your return request is approved and passes UBAP's in-person quality check, and you choose a Cash Refund, your refund is paid to you directly in cash at UBAP upon presentation of your physical Official Receipt. If you choose an Exchange, no monetary refund is issued; the System records only that the item was exchanged.
                        </p>
                    </section>

                    {{-- 6. Data Sharing and Disclosure --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">6. Data Sharing and Disclosure</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            We do not sell, rent, or trade your personal data. Your personal data may only be shared or disclosed under the following circumstances:
                        </p>
                        <ul class="mt-3 list-disc space-y-2 pl-5 text-base leading-8 text-slate-600">
                            <li>
                                <strong>UBAP Admin:</strong> Accesses order details, stock, pricing, review data, and return/exchange/refund records (including uploaded photos/videos, appointment slots, and inspection notes) strictly to manage inventory, fulfill orders, and execute in-person customer support.
                            </li>
                            <li>
                                <strong>StraCom Admin:</strong> Does not have access to individual user personal, payment, or return/refund data. Role is strictly limited to managing visual assets (e.g., banners, landing page content, product photos).
                            </li>
                            <li>
                                <strong>Super Administrator:</strong> Accesses account and role-management data for system administration, and maintains execution permissions as required.
                            </li>
                            <li>
                                <strong>Legal & Compliance:</strong> When required or authorized by law, regulation, court order, or valid requests from competent authorities (such as the NPC, BIR, or law enforcement).
                            </li>
                        </ul>
                    </section>

                    {{-- 7. Data Storage and Security --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">7. Data Storage and Security</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            We implement reasonable and appropriate organizational, physical, and technical security measures to protect your personal data, including password hashing, role-based authorization controls, and secure storage for uploaded user content. Because all transactions use Cash on Pickup, no payment card details ever pass through or store on our web servers.
                        </p>
                    </section>

                    {{-- 8. Data Retention --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">8. Data Retention</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            We retain personal data only for as long as necessary to fulfill its purpose or comply with accounting and legal retention policies:
                        </p>
                        <ul class="mt-3 list-disc space-y-2 pl-5 text-base leading-8 text-slate-600">
                            <li>Account and profile data are kept as long as your account remains active.</li>
                            <li>Order and transaction details are kept according to Philippine tax, audit, and accounting rules.</li>
                            <li>Return, refund, and uploaded photo/video proof files are retained for the duration needed to fulfill quality assurance and dispute resolution, after which media files are securely deleted or anonymized.</li>
                        </ul>
                    </section>

                    {{-- 9. Your Rights as a Data Subject --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">9. Your Rights as a Data Subject</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            Under Republic Act No. 10173, you have the right to be informed, right to access, right to object, right to rectification, right to erasure or blocking, right to data portability, right to file a complaint with the NPC, and right to damages. To exercise these rights, please reach out through our contact details below.
                        </p>
                    </section>

