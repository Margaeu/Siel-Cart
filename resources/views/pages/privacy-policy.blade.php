                    {{-- 1. Introduction --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">1. Introduction</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            Siel Cart is the official online merchandise platform operated under the auxiliary and business operations mandate of Central Luzon State University (CLSU), through its Office of Business Affairs. We are committed to protecting the privacy and personal data of our users — external customers, students, faculty, staff, and other members of the CLSU community — in accordance with Republic Act No. 10173, otherwise known as the Data Privacy Act of 2012, its Implementing Rules and Regulations, and other applicable issuances of the National Privacy Commission (NPC).
                        </p>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            This Data Privacy Notice and Consent describes what personal data we collect through the System, why we collect it, how it is used, stored, shared, and protected, and what rights you have as a data subject.
                        </p>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            Please read this Notice carefully before creating an account, placing an order, or otherwise using the System.
                        </p>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            This Notice is issued consistent with, and is intended to operate alongside, the University’s existing data privacy infrastructure — including the CLSU Data Privacy Office and the University’s designated Data Protection Officer (DPO) — as reflected in other official CLSU systems.
                        </p>
                    </section>

                    {{-- 2. Scope and Coverage of the System --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">2. Scope and Coverage of the System</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            The CLSU Siel Cart is an order and pickup-only platform. It allows verified users to browse and order official CLSU merchandise, apparel, academic regalia, memorabilia, and daily accessories online and pick up their items within the CLSU campus.
                        </p>
                        <p class="mt-3 text-base leading-8 text-slate-600">This Notice covers all personal data processed through:</p>
                        <ul class="mt-3 list-disc space-y-2 pl-5 text-base leading-8 text-slate-600">
                            <li>Account registration, login, and profile management;</li>
                            <li>Product browsing, ordering, and order fulfillment;</li>
                            <li>Product reviews and ratings submitted after order pickup;</li>
                            <li>Cash-on-pickup payment recording;</li>
                            <li>Account deletion; and</li>
                            <li>Administrative functions performed by authorized University personnel, including UBAP Admin, StratCom Admin, and Super Admin roles.</li>
                        </ul>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            Because the System is pickup-only, no delivery or courier-related personal data, such as a shipping address for a third-party courier, is collected or shared with any logistics provider.
                        </p>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            All payments and cash refunds are completed in person at UBAP. The System is used to place orders; to file, track, and schedule pickup. The physical inspection of returned items, the quality check, and the release of cash refunds are completed in person at UBAP. The System does not process online payments or automatic online refunds.
                        </p>
                    </section>

                    {{-- 3. Personal Data We Collect --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">3. Personal Data We Collect</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            We collect only the personal data reasonably necessary to operate the System. Depending on how you use Siel Cart, this may include:
                        </p>

                        <h3 class="mt-4 text-lg font-semibold text-slate-800">3.1 Account and Profile Information</h3>
                        <ul class="mt-2 list-disc space-y-1 pl-5 text-base leading-8 text-slate-600">
                            <li>Full name;</li>
                            <li>Email address, whether institutional or personal;</li>
                            <li>Phone number, if provided;</li>
                            <li>Birth date; and</li>
                            <li>Account credentials. Your password is encrypted/hashed and is never visible, even to System administrators.</li>
                        </ul>

                        <h3 class="mt-4 text-lg font-semibold text-slate-800">3.2 Order and Transaction Information</h3>
                        <ul class="mt-2 list-disc space-y-1 pl-5 text-base leading-8 text-slate-600">
                            <li>Order details, including items purchased, quantity, price, and order status;</li>
                            <li>Claim number and pickup confirmation;</li>
                            <li>Payment status;</li>
                            <li>Amount due and amount paid; and</li>
                            <li>Official Receipt (OR) number issued by UBAP upon payment.</li>
                        </ul>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            The System does not collect or store card numbers, e-wallet credentials, banking information, or other online payment credentials because payment is made in cash at pickup. The UBAP Admin manually records the applicable OR number in the System.
                        </p>

                        <h3 class="mt-4 text-lg font-semibold text-slate-800">3.3 Reviews and Feedback</h3>
                        <p class="mt-2 text-base leading-8 text-slate-600">
                            If you choose to leave a product review after picking up your order, we collect the content of your review, your rating, and the date submitted. Reviews are associated with your account and may be visible to other users of the System.
                        </p>

                        <h3 class="mt-4 text-lg font-semibold text-slate-800">3.4 Return, Exchange, and Refund Information</h3>
                        <p class="mt-2 text-base leading-8 text-slate-600">
                            Refund or exchange requests will only be accepted for items that are <strong>defective, damaged, or incorrectly sent by the seller</strong>. Please proceed to the <strong>UBAP Office</strong> to have your request processed. Bring the item along with proof of purchase (if available) to help speed up the transaction.
                        </p>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            <strong>Note:</strong> Change of mind is not a valid reason for refund or exchange.
                        </p>

                    </section>

                    {{-- 4. Why We Collect and Process Your Personal Data --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">4. Why We Collect and Process Your Personal Data</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            We process your personal data for the following purposes, consistent with the principles of transparency, legitimate purpose, and proportionality under the DPA:
                        </p>
                        <ul class="mt-3 list-disc space-y-2 pl-5 text-base leading-8 text-slate-600">
                            <li>To verify your identity and confirm that you meet the applicable minimum age requirement;
                                <ul class="mt-2 list-disc pl-5">
                                    <li>The applicable minimum age to create a Siel Cart account is 13 years old.</li>
                                </ul>
                            </li>
                            <li>To process, fulfill, and allow you to pick up your orders within CLSU;</li>
                            <li>To allow you to submit and view product reviews;</li>
                            <li>To communicate with you regarding your account, orders, or System updates;</li>
                            <li>To maintain the security, integrity, and proper functioning of the System;</li>
                            <li>To manage account status, including deletion;</li>
                            <li>To prevent account actions that could interfere with unresolved orders;</li>
                            <li>To maintain appropriate administrative and transaction records; and</li>
                            <li>To comply with applicable laws, University policies, and legitimate requests from government authorities.</li>
                        </ul>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            The legal bases for this processing include your consent, the necessity of processing to fulfill a transaction you have requested, and the legitimate interests of the University in operating an official campus merchandise service.
                        </p>
                    </section>

                    {{-- 5. Payment Information — Cash on Pickup --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">5. Payment Information — Cash on Pickup</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            Siel Cart does not accept or process online payments, and no third-party payment gateway is used. All orders are paid for in cash at the time of pickup at UBAP.
                        </p>
                        <h3 class="mt-4 text-lg font-semibold text-slate-800">5.1 What Payment Data We Collect</h3>
                        <p class="mt-2 text-base leading-8 text-slate-600">Because payment happens in person, the System does not collect or store:</p>
                        <ul class="mt-2 list-disc space-y-1 pl-5 text-base leading-8 text-slate-600">
                            <li>Credit or debit card numbers;</li>
                            <li>E-wallet credentials;</li>
                            <li>Banking information; or</li>
                            <li>Other online payment credentials.</li>
                        </ul>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            The System records only the payment information necessary for order and transaction records, including:
                        </p>
                        <ul class="mt-2 list-disc space-y-1 pl-5 text-base leading-8 text-slate-600">
                            <li>Amount due;</li>
                            <li>Amount paid; and</li>
                            <li>Official Receipt (OR) number issued by UBAP.</li>
                        </ul>
                    </section>

                    {{-- 6. Data Sharing and Disclosure --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">6. Data Sharing and Disclosure</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">We do not sell, rent, or trade your personal data.</p>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            Your personal data may only be shared or disclosed under the following circumstances:
                        </p>
                        <ul class="mt-3 list-disc space-y-2 pl-5 text-base leading-8 text-slate-600">
                            <li>With authorized University personnel who require access to perform their official duties, including:
                                <ul class="mt-2 list-disc space-y-2 pl-5">
                                    <li><strong>UBAP Admin:</strong> Order details, stock, pricing, payment-related records, review data, inventory management, and processing return requests;</li>
                                    <li><strong>StratCom Admin:</strong> System visual content and related administrative functions, without access to individual users' personal, payment, or return/refund data unless specifically authorized;</li>
                                    <li><strong>Super Admin/Administrator:</strong> account and role-management data and other permissions necessary to administer the System;</li>
                                </ul>
                            </li>
                            <li>When required or authorized by law, regulation, court order, or a valid request from a competent government authority;</li>
                            <li>To protect the rights, property, or safety of the University, its users, or the public where disclosure is reasonably necessary.</li>
                        </ul>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            We do not transfer personal data outside the Philippines except to the extent that our hosting provider processes data through servers that may be located outside the country, in which case such providers are contractually and legally bound to maintain data protection standards consistent with applicable requirements.
                        </p>
                    </section>

                    {{-- 7. Data Storage and Security --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">7. Data Storage and Security</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            We implement reasonable and appropriate organizational, physical, and technical security measures to protect your personal data against accidental or unlawful destruction, alteration, disclosure, or access, including:
                        </p>
                        <ul class="mt-3 list-disc space-y-2 pl-5 text-base leading-8 text-slate-600">
                            <li>Encryption or hashing of passwords;</li>
                            <li>Role-based access controls;</li>
                            <li>Secure, access-controlled storage of uploaded files;</li>
                            <li>Appropriate restrictions on administrative access to personal data;</li>
                            <li>Protection of account and transaction records; and</li>
                            <li>No online payment or card-data collection, transmission, or storage.</li>
                        </ul>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            While we take reasonable steps to protect your personal data, no method of electronic storage or transmission is 100% secure. You also play a role in protecting your account by keeping your password confidential and not sharing your login credentials with others.
                        </p>
                    </section>

                    {{-- 8. Data Retention and Account Lifecycle --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">8. Data Retention and Account Lifecycle</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            We retain personal data only for as long as necessary to fulfill the purposes described in this Notice, comply with legal and accounting obligations, maintain transaction records, or resolve disputes, after which applicable data will be securely disposed of or anonymized.
                        </p>
                        <p class="mt-3 text-base leading-8 text-slate-600">The following account lifecycle applies:</p>

                        <h3 class="mt-4 text-lg font-semibold text-slate-800">8.1 Active Account</h3>
                        <p class="mt-2 text-base leading-8 text-slate-600">
                            An <strong>Active</strong> account may log in, manage its profile, place orders, and use other authorized customer functions.
                        </p>

                        <h3 class="mt-4 text-lg font-semibold text-slate-800">8.2 Deleted Account</h3>
                        <p class="mt-2 text-base leading-8 text-slate-600">
                            A customer may request account deletion only after all unresolved orders have been completed or cancelled.
                        </p>
                        <p class="mt-3 text-base leading-8 text-slate-600">Once an account is deleted:</p>
                        <ul class="mt-2 list-disc space-y-1 pl-5 text-base leading-8 text-slate-600">
                            <li>The customer can no longer log in;</li>
                            <li>The customer cannot reactivate the account through the normal customer interface;</li>
                            <li>The account is identified as <strong>Deleted Account</strong> where necessary for administrative or transaction records;</li>
                            <li>Personal data will be removed or anonymized where applicable; and</li>
                            <li>Any reviews you submitted are retained and displayed under the name &quot;Deleted User&quot; rather than being removed.</li>
                        </ul>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            Deletion does not require the removal of information that must be retained for legal, accounting, tax, audit, transaction, dispute-resolution, or other legitimate recordkeeping purposes.
                        </p>

                        <h3 class="mt-4 text-lg font-semibold text-slate-800">8.3 Order and Transaction Records</h3>
                        <p class="mt-2 text-base leading-8 text-slate-600">
                            Order and transaction records are retained for the period required under applicable Philippine tax, audit, accounting, and institutional recordkeeping requirements.
                        </p>
                    </section>

                    {{-- 9. Your Rights as a Data Subject --}}
                    <section>
                        <h2 class="text-xl font-bold text-slate-900">9. Your Rights as a Data Subject</h2>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            Under the Data Privacy Act of 2012, you have the following rights with respect to your personal data:
                        </p>
                        <ul class="mt-3 list-disc space-y-2 pl-5 text-base leading-8 text-slate-600">
                            <li><strong>Right to be informed</strong> — to know that your personal data will be, is being, or has been processed;</li>
                            <li><strong>Right to access</strong> — to obtain a copy of your personal data held by the System;</li>
                            <li><strong>Right to object</strong> — to object to the processing of your personal data under applicable circumstances;</li>
                            <li><strong>Right to rectification</strong> — to dispute and have corrected inaccurate or outdated personal data;</li>
                            <li><strong>Right to erasure or blocking</strong> — to request the removal or blocking of personal data under circumstances allowed by law;</li>
                            <li><strong>Right to data portability</strong> — to obtain a copy of your data in an electronic format, where technically feasible;</li>
                            <li><strong>Right to file a complaint</strong> — to lodge a complaint with the CLSU Data Privacy Office or the National Privacy Commission (NPC) if you believe your rights have been violated; and</li>
                            <li><strong>Right to damages</strong> — to seek applicable remedies for damages sustained due to unlawful or unauthorized processing.</li>
                        </ul>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            Requests concerning account deletion remain subject to unresolved-order restrictions and applicable legal or record-retention requirements.
                        </p>
                        <p class="mt-3 text-base leading-8 text-slate-600">
                            To exercise any of these rights, please contact us using the details in <strong>Section 11</strong>.
                        </p>
                    </section>

